// Command cborgen emits typed readers for the explicitly supported roots. It
// checks the source types before writing; an unmapped field stops generation.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

func main() {
	check := flag.Bool("check", false, "check that generated output is current")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	ps, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports | packages.NeedDeps}, "github.com/NethermindEth/juno/core")
	if err != nil {
		return err
	}
	if packages.PrintErrors(ps) != 0 {
		return fmt.Errorf("loading core")
	}
	p := ps[0].Types
	var b, schema bytes.Buffer
	schema.WriteString("// Code generated by cborgen; DO NOT EDIT.\n// Package cborschema owns the immutable field tables used by core typed readers.\npackage cborschema\n\nimport \"github.com/NethermindEth/juno/utils/cbor/cursor\"\n")
	b.WriteString("// Code generated by cborgen; DO NOT EDIT.\npackage core\n\nimport (\"github.com/NethermindEth/juno/core/internal/cborschema\"; \"github.com/NethermindEth/juno/utils/cbor/cursor\"; \"github.com/NethermindEth/juno/utils/cbor/fastcbor\")\n")
	for _, name := range []string{"GasPrice", "Header"} {
		st, ok := p.Scope().Lookup(name).Type().Underlying().(*types.Struct)
		if !ok {
			return fmt.Errorf("%s is not a struct", name)
		}
		var reads, zeros, names []string
		for i := 0; i < st.NumFields(); i++ {
			f := st.Field(i)
			if !f.Exported() || f.Embedded() {
				return fmt.Errorf("unsupported field %s.%s", name, f.Name())
			}
			wire := strings.Split(reflect.StructTag(st.Tag(i)).Get("cbor"), ",")[0]
			if wire == "" {
				wire = f.Name()
			}
			names = append(names, wire)
			typ := types.TypeString(f.Type(), func(p *types.Package) string { return p.Path() })
			var read, zero string
			switch typ {
			case "uint64":
				read = "cborReadUint64(c, &dst." + f.Name() + ")"
				zero = "dst." + f.Name() + " == 0"
			case "string":
				read = "cborReadString(c, &dst." + f.Name() + ")"
				zero = "dst." + f.Name() + " == \"\""
			case "github.com/NethermindEth/juno/core.L1DAMode":
				read = "cborReadMode(c, &dst." + f.Name() + ")"
				zero = "dst." + f.Name() + " == 0"
			default:
				switch {
				case strings.HasPrefix(typ, "*github.com/NethermindEth/juno/core/felt."):
					read = "cborReadFelt(c, &dst." + f.Name() + ")"
					zero = "dst." + f.Name() + " == nil"
				case f.Name() == "Signatures" && strings.HasPrefix(typ, "[][]*github.com/NethermindEth/juno/core/felt."):
					read = "cborReadSignatures(c, &dst.Signatures)"
					zero = "dst.Signatures == nil"
				case typ == "*github.com/NethermindEth/juno/core.GasPrice" && name == "Header" && f.Name() == "L1DataGasPrice":
					read = "cborReadGasPriceSlot(c, &dst.L1DataGasPrice, &prices, 0)"
					zero = "dst.L1DataGasPrice == nil"
				case typ == "*github.com/NethermindEth/juno/core.GasPrice" && name == "Header" && f.Name() == "L2GasPrice":
					read = "cborReadGasPriceSlot(c, &dst.L2GasPrice, &prices, 1)"
					zero = "dst.L2GasPrice == nil"
				default:
					return fmt.Errorf("unmapped field %s.%s (%s)", name, f.Name(), typ)
				}
			}
			reads = append(reads, read)
			zeros = append(zeros, zero)
		}
		if err := emitFields(&schema, name, names); err != nil {
			return err
		}
		fmt.Fprintf(&b, "\nfunc cborZero%s(dst *%s) bool { return %s }\n", name, name, strings.Join(zeros, " && "))
		fmt.Fprintf(&b, "\nfunc cborRead%s(c *cursor.Cursor, dst *%s) error {\n", name, name)
		if name == "Header" {
			b.WriteString("var prices *[2]GasPrice\n")
		}
		fmt.Fprintf(&b, "s,err:=cborschema.Open%s(c)\nfor err==nil {\nvar field int\nfield,err=c.NextField(&s)\nswitch field {\ncase cursor.Done: return err\n", name)
		for i, read := range reads {
			fmt.Fprintf(&b, "case %d: err=%s\n", i, read)
		}
		b.WriteString("default: err=c.Skip()\n}\n}\nreturn err\n}\n")
	}
	b.WriteString(`
func cborReadGasPriceSlot(c *cursor.Cursor, dst **GasPrice, shared **[2]GasPrice, slot int) error {
	if c.Null() {
		*dst = nil
		return nil
	}
	if *shared == nil {
		*shared = new([2]GasPrice)
	}
	value := &(*shared)[slot]
	if err := cborReadGasPrice(c, value); err != nil {
		return err
	}
	*dst = value
	return nil
}

// cborClearHeader drops every partially decoded field after an error.
func cborClearHeader(dst *Header) { *dst=Header{} }

// DecodeHeaderFirst reads one header, enforcing fastcbor's zero-destination contract.
func DecodeHeaderFirst(data []byte, dst *Header) ([]byte,error) {
 if !cborZeroHeader(dst) {return nil,&fastcbor.DecodeError{Kind:fastcbor.ErrUnsupported,Detail:"the destination is not the zero value"}}
 c:=cursor.NewCursor(data)
 if err:=cborReadHeader(&c,dst);err!=nil {cborClearHeader(dst);return nil,err}
 return c.Remaining(),nil
}

// DecodeHeader reads exactly one header and clears the destination on failure.
func DecodeHeader(data []byte,dst *Header) error {
 rest,err:=DecodeHeaderFirst(data,dst)
 if err==nil && len(rest)!=0 {cborClearHeader(dst);return &fastcbor.DecodeError{Kind:fastcbor.ErrExtraneousData,Extra:len(rest)}}
 return err
}

// RegisterTypedCBORReaders installs the currently generated typed entry points.
func RegisterTypedCBORReaders() { fastcbor.RegisterTyped[Header](DecodeHeaderFirst) }
`)
	outputs := []struct {
		path string
		buf  *bytes.Buffer
	}{
		{"core/internal/cborschema/fields_generated.go", &schema},
		{"core/cbor_readers_generated.go", &b},
	}
	for _, output := range outputs {
		out, err := format.Source(output.buf.Bytes())
		if err != nil {
			return fmt.Errorf("format %s: %w", output.path, err)
		}
		if check {
			old, err := os.ReadFile(output.path)
			if err != nil {
				return err
			}
			if !bytes.Equal(old, out) {
				return fmt.Errorf("%s is stale; run go run ./utils/cbor/cmd/cborgen", output.path)
			}
		} else {
			if err := os.MkdirAll(filepath.Dir(output.path), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(output.path, out, 0644); err != nil {
				return err
			}
		}
	}
	return nil
}

// emitFields does every metadata calculation at generation time. The resulting
// literals are also the inputs to the field-table ownership proofs.
func emitFields(b *bytes.Buffer, name string, names []string) error {
	if len(names) > 64 {
		return fmt.Errorf("%s: more than 64 fields", name)
	}
	type entry struct {
		encoded      string
		index        int
		words, masks [3]uint64
	}
	entries := make([]entry, len(names))
	folded := make(map[string]bool, len(names))
	for i, key := range names {
		if len(key) >= 256 {
			return fmt.Errorf("%s: field name too long: %q", name, key)
		}
		for _, c := range []byte(key) {
			if c >= 128 {
				return fmt.Errorf("%s: non-ASCII field: %q", name, key)
			}
		}
		lower := strings.ToLower(key)
		if folded[lower] {
			return fmt.Errorf("%s: duplicate field ignoring case: %q", name, key)
		}
		folded[lower] = true
		head := []byte{0x60 | byte(len(key))}
		if len(key) >= 24 {
			head = []byte{0x78, byte(len(key))}
		}
		e := entry{encoded: string(head) + key, index: i}
		for j := 0; j < len(e.encoded) && j < 24; j++ {
			e.words[j/8] |= uint64(e.encoded[j]) << (j % 8 * 8)
			e.masks[j/8] |= 0xff << (j % 8 * 8)
		}
		entries[i] = e
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].encoded < entries[j].encoded })
	fmt.Fprintf(b, "\nvar cbor%sFields = cborMake%sFields()\n\nfunc cborMake%sFields() *cursor.Fields {\n return cursor.NewStaticFields([]string{\n", name, name, name)
	for _, key := range names {
		fmt.Fprintf(b, "%q,\n", key)
	}
	b.WriteString("}, []cursor.StaticField{\n")
	for _, e := range entries {
		fmt.Fprintf(b, "{Words:[3]uint64{%#x,%#x,%#x},Masks:[3]uint64{%#x,%#x,%#x},Encoded:%q,Index:%d,Bit:%#x,Short:%t},\n", e.words[0], e.words[1], e.words[2], e.masks[0], e.masks[1], e.masks[2], e.encoded, e.index, uint64(1)<<e.index, len(e.encoded) <= 24)
	}
	b.WriteString("})\n}\n")
	fmt.Fprintf(b, "\n// Open%s opens a record using its private immutable field table.\nfunc Open%s(c *cursor.Cursor) (cursor.Struct, error) { return c.OpenStruct(cbor%sFields) }\n", name, name, name)
	return nil
}
