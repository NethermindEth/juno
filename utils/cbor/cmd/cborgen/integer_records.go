package main

import (
	"bytes"
	"fmt"
	"go/types"
	"reflect"
	"slices"
	"strconv"
	"strings"
)

// emitIntegerRecord currently supports the []int fields used by block indexes.
// It reads keys and field shapes from the source and emits direct dispatch, with
// no runtime offsets, field table, reflection or allocation hooks.
func emitIntegerRecord(p *types.Package, name string) (*bytes.Buffer, error) {
	obj := p.Scope().Lookup(name)
	if obj == nil {
		return nil, fmt.Errorf("missing integer-keyed record %s", name)
	}
	st, ok := obj.Type().Underlying().(*types.Struct)
	if !ok || st.NumFields() == 0 || st.NumFields() > 64 {
		return nil, fmt.Errorf("%s must be a struct with 1 to 64 integer-keyed fields", name)
	}
	keys := make([]uint64, st.NumFields())
	zeros := make([]string, st.NumFields())
	seen := make(map[uint64]bool, st.NumFields())
	for i := 0; i < st.NumFields(); i++ {
		field := st.Field(i)
		parts := strings.Split(reflect.StructTag(st.Tag(i)).Get("cbor"), ",")
		key, err := strconv.ParseUint(parts[0], 10, 63)
		if !field.Exported() || field.Embedded() || err != nil || !slices.Contains(parts[1:], "keyasint") || seen[key] {
			return nil, fmt.Errorf("%s.%s must have a distinct unsigned int64 CBOR key", name, field.Name())
		}
		for _, option := range parts[1:] {
			if option != "keyasint" && option != "omitempty" {
				return nil, fmt.Errorf("unsupported CBOR option %q on %s.%s", option, name, field.Name())
			}
		}
		if !types.Identical(field.Type(), types.NewSlice(types.Typ[types.Int])) {
			return nil, fmt.Errorf("unmapped integer-keyed field %s.%s (%s)", name, field.Name(), field.Type())
		}
		seen[key] = true
		keys[i] = key
		zeros[i] = "dst." + field.Name() + " == nil"
	}
	var b bytes.Buffer
	b.WriteString(`// Code generated by cborgen; DO NOT EDIT.
package core
import (
 "github.com/NethermindEth/juno/utils/cbor/cborerr"
 "github.com/NethermindEth/juno/utils/cbor/cursor"
)
`)
	fmt.Fprintf(&b, "\nfunc cborZero%s(dst *%s) bool { return %s }\n", name, name, strings.Join(zeros, " && "))
	fmt.Fprintf(&b, "\nfunc cborRead%s(c *cursor.Cursor, dst *%s) error {\n", name, name)
	b.WriteString(`if c.Null() {return nil}
 count,err:=c.MapLen()
 if err!=nil {return err}
 var seen uint64
 for ;count>0;count-- {
  key,unsigned,err:=cborReadIntegerKey(c)
  if err!=nil {return err}
  if !unsigned {
   if err:=c.Skip();err!=nil {return err}
   continue
  }
  switch key {
`)
	for i, key := range keys {
		fmt.Fprintf(&b, `case %d:
   if seen&%#x!=0 {err=c.Skip()} else {
    seen|=%#x
    err=cborReadInts(c,&dst.%s)
   }
`, key, uint64(1)<<i, uint64(1)<<i, st.Field(i).Name())
	}
	b.WriteString("default: err=c.Skip()\n}\nif err!=nil {return err}\n}\nc.Leave()\nreturn nil\n}\n")
	fmt.Fprintf(&b, "\nfunc cborClear%s(dst *%s) { *dst=%s{} }\n", name, name, name)
	fmt.Fprintf(&b, `
// Decode%sFirst reads one index record into a zero destination.
// Parse failures clear the destination; nonzero destinations are preserved.
func Decode%sFirst(data []byte,dst *%s) ([]byte,error) {
 if !cborZero%s(dst) {return nil,&cborerr.DecodeError{Kind:cborerr.ErrUnsupported,Detail:"the destination is not the zero value"}}
 c:=cursor.NewCursor(data)
 if err:=cborRead%s(&c,dst);err!=nil {cborClear%s(dst);return nil,err}
 return c.Remaining(),nil
}

// Decode%s reads exactly one index record, rejecting trailing data.
func Decode%s(data []byte,dst *%s) error {
 rest,err:=Decode%sFirst(data,dst)
 if err==nil && len(rest)!=0 {cborClear%s(dst);return &cborerr.DecodeError{Kind:cborerr.ErrExtraneousData,Extra:len(rest)}}
 return err
}
`, name, name, name, name, name, name, name, name, name, name, name)
	return &b, nil
}
