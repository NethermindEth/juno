package main

import (
	"bytes"
	"fmt"
	"go/types"
	"reflect"
	"strings"
)

// Header projections share a discard skeleton, but their lookup tables contain
// only materialized fields. NextWanted consumes every other value, including
// later occurrences of an already read field.
func emitHeaderProjections(p *types.Package) (*bytes.Buffer, *bytes.Buffer, error) {
	var readers, schema bytes.Buffer
	readers.WriteString(`// Code generated by cborgen; DO NOT EDIT.
package core
import (
 "github.com/NethermindEth/juno/core/internal/cborprojections"
 "github.com/NethermindEth/juno/utils/cbor/cborerr"
 "github.com/NethermindEth/juno/utils/cbor/cursor"
 "github.com/NethermindEth/juno/utils/cbor/fastcbor"
)
`)
	schema.WriteString(`// Code generated by cborgen; DO NOT EDIT.
// Package cborprojections owns immutable lookup tables for typed Header projections.
package cborprojections
import "github.com/NethermindEth/juno/utils/cbor/cursor"
`)
	header := p.Scope().Lookup("Header").Type().Underlying().(*types.Struct)
	skeletonType := p.Scope().Lookup("discardedHeaderSkeleton").Type()
	skeleton := skeletonType.Underlying().(*types.Struct)
	discard := p.Scope().Lookup("discardedCBOR").Type()
	marker, ok := discard.Underlying().(*types.Struct)
	if !ok || marker.NumFields() != 0 {
		return nil, nil, fmt.Errorf("discardedCBOR must be an empty struct")
	}
	if skeleton.NumFields() != header.NumFields() {
		return nil, nil, fmt.Errorf("discardedHeaderSkeleton must cover every Header field")
	}
	headerFields := make(map[string]types.Type, header.NumFields())
	for i := 0; i < header.NumFields(); i++ {
		wire, err := projectionWireName(header, i)
		if err != nil {
			return nil, nil, err
		}
		headerFields[wire] = header.Field(i).Type()
	}
	seen := make(map[string]bool, skeleton.NumFields())
	for i := 0; i < skeleton.NumFields(); i++ {
		wire, err := projectionWireName(skeleton, i)
		if err != nil {
			return nil, nil, err
		}
		if headerFields[wire] == nil || seen[wire] || !types.Identical(skeleton.Field(i).Type(), discard) {
			return nil, nil, fmt.Errorf("invalid discardedHeaderSkeleton field %s", skeleton.Field(i).Name())
		}
		seen[wire] = true
	}
	var registrations []string
	for _, name := range []string{
		"headerHashProjection", "headerGlobalStateRootProjection", "headerTransactionCountProjection",
		"headerTimestampProjection", "headerHashAndStateRootProjection",
	} {
		st := p.Scope().Lookup(name).Type().Underlying().(*types.Struct)
		if st.NumFields() < 2 || !st.Field(0).Embedded() || !types.Identical(st.Field(0).Type(), skeletonType) {
			return nil, nil, fmt.Errorf("%s must embed discardedHeaderSkeleton", name)
		}
		stem := strings.ToUpper(name[:1]) + name[1:]
		var names, reads, zeros []string
		for i := 1; i < st.NumFields(); i++ {
			wire, err := projectionWireName(st, i)
			if err != nil {
				return nil, nil, err
			}
			f := st.Field(i)
			fieldType := f.Type()
			// Timestamp intentionally preserves presence with *uint64. Other
			// selected fields retain the Header representation exactly.
			if name == "headerTimestampProjection" && f.Name() == "Timestamp" {
				ptr, ok := fieldType.(*types.Pointer)
				if !ok || !types.Identical(ptr.Elem(), types.Typ[types.Uint64]) {
					return nil, nil, fmt.Errorf("%s.Timestamp must be *uint64", name)
				}
				fieldType = ptr.Elem()
			}
			if headerFields[wire] == nil || !types.Identical(fieldType, headerFields[wire]) {
				return nil, nil, fmt.Errorf("%s.%s does not match Header key %q", name, f.Name(), wire)
			}
			var read, zero string
			switch types.TypeString(f.Type(), func(p *types.Package) string { return p.Path() }) {
			case "uint64":
				read, zero = "cborReadUint64", " == 0"
			case "*uint64":
				read, zero = "cborReadUint64Pointer", " == nil"
			case "*github.com/NethermindEth/juno/core/felt.Felt":
				read, zero = "cborReadFelt", " == nil"
			default:
				return nil, nil, fmt.Errorf("unmapped projection field %s.%s (%s)", name, f.Name(), f.Type())
			}
			names = append(names, wire)
			reads = append(reads, read+"(c, &dst."+f.Name()+")")
			zeros = append(zeros, "dst."+f.Name()+zero)
		}
		if err := emitFields(&schema, stem, names); err != nil {
			return nil, nil, err
		}
		fmt.Fprintf(&readers, "\nfunc cborZero%s(dst *%s) bool { return %s }\n", stem, name, strings.Join(zeros, " && "))
		fmt.Fprintf(&readers, "\nfunc cborRead%s(c *cursor.Cursor, dst *%s) error {\n", stem, name)
		readers.WriteString("if err:=cborReadProjectionTag(c);err!=nil {return err}\n")
		fmt.Fprintf(&readers, "s,err:=cborprojections.Open%s(c)\nfor err==nil {\nvar field int\nfield,err=c.NextWanted(&s)\nswitch field {\ncase cursor.Done: return err\n", stem)
		for i, read := range reads {
			fmt.Fprintf(&readers, "case %d: err=%s\n", i, read)
		}
		readers.WriteString("}\n}\nreturn err\n}\n")
		fmt.Fprintf(&readers, "\nfunc cborClear%s(dst *%s) { *dst=%s{} }\n", stem, name, name)
		fmt.Fprintf(&readers, `
func decode%sFirst(data []byte, dst *%s) ([]byte,error) {
 if !cborZero%s(dst) {return nil,&cborerr.DecodeError{Kind:cborerr.ErrUnsupported,Detail:"the destination is not the zero value"}}
 c:=cursor.NewCursor(data)
 if err:=cborRead%s(&c,dst);err!=nil {cborClear%s(dst);return nil,err}
 return c.Remaining(),nil
}
`, stem, name, stem, stem, stem)
		registrations = append(registrations, fmt.Sprintf("fastcbor.RegisterTyped[%s](decode%sFirst)", name, stem))
	}
	fmt.Fprintf(&readers, "\nfunc registerTypedHeaderProjections() {\n%s\n}\n", strings.Join(registrations, "\n"))
	return &readers, &schema, nil
}

func projectionWireName(st *types.Struct, i int) (string, error) {
	f := st.Field(i)
	if !f.Exported() || f.Embedded() {
		return "", fmt.Errorf("unsupported projection field %s", f.Name())
	}
	parts := strings.Split(reflect.StructTag(st.Tag(i)).Get("cbor"), ",")
	for _, option := range parts[1:] {
		if option != "omitempty" {
			return "", fmt.Errorf("unsupported CBOR option %q on %s", option, f.Name())
		}
	}
	if parts[0] == "-" {
		return "", fmt.Errorf("discard tag on projection field %s", f.Name())
	}
	if parts[0] == "" {
		return f.Name(), nil
	}
	return parts[0], nil
}
