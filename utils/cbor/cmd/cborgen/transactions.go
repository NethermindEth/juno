func transactionRead(t types.Type) (string, error) {
	switch types.TypeString(t, func(p *types.Package) string { return p.Path() }) {
	case "*github.com/NethermindEth/juno/core.TransactionVersion":
		elem := t.(*types.Pointer).Elem().Underlying()
		a, ok := elem.(*types.Array)
		if !ok || a.Len() != 4 || !types.Identical(a.Elem(), types.Typ[types.Uint64]) {
			break
		}
		return "cborReadTransactionVersion", nil
	case "github.com/NethermindEth/juno/core.DataAvailabilityMode":
		if !types.Identical(t.Underlying(), types.Typ[types.Uint32]) {
			break
		}
		return "cborReadDataAvailabilityMode", nil
	case "map[github.com/NethermindEth/juno/core.Resource]github.com/NethermindEth/juno/core.ResourceBounds":
		if !types.Identical(t.(*types.Map).Key().Underlying(), types.Typ[types.Uint32]) {
			break
		}
		return "cborReadResourceBoundsMap", nil
	case "[]github.com/NethermindEth/juno/core/felt.Felt":
		return "cborReadPlainFeltValues", nil
	default:
		read, _, err := receiptField(t)
		return read, err
	}
	return "", fmt.Errorf("unmapped transaction field type %s", t)
}
