`)
	union := make(map[string]types.Type)
	for _, name := range append([]string{"ResourceBounds"}, transactionTypes...) {
		st := p.Scope().Lookup(name).Type().Underlying().(*types.Struct)
		fields, err := transactionFields(st, "")
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", name, err)
		}
		var names, reads []string
		for _, f := range fields {
			read, err := transactionRead(f.typ)
			if err != nil {
				return nil, nil, fmt.Errorf("%s.%s: %w", name, f.path, err)
			}
			names = append(names, f.wire)
			reads = append(reads, read+"(c, &dst."+f.path+")")
			if name != "ResourceBounds" {
				if prior := union[f.wire]; prior != nil && !types.Identical(prior, f.typ) {
					return nil, nil, fmt.Errorf("transaction key %q has different types", f.wire)
				}
				union[f.wire] = f.typ
			}
		}
		if err := emitFields(&schema, name, names); err != nil {
			return nil, nil, err
		}
		fmt.Fprintf(&readers, "func cborRead%s(c *cursor.Cursor, dst *%s) error {\ns,err:=cbortransactions.Open%s(c)\nfor err==nil {\nvar field int\nfield,err=c.NextField(&s)\nswitch field {\ncase cursor.Done: return err\n", name, name, name)
		for i, read := range reads {
			fmt.Fprintf(&readers, "case %d: err=%s\n", i, read)
		}
		readers.WriteString("default: err=c.Skip()\n}\n}\nreturn err\n}\n")
	}
	// The projection materializes a value felt and discards the union of every
	// other wire key. It deliberately accepts any single enclosing tag > 3.
	projection := p.Scope().Lookup("transactionHashProjection").Type().Underlying().(*types.Struct)
	discard := p.Scope().Lookup("discardedCBOR").Type()
	if projection.NumFields() != len(union) {
		return nil, nil, fmt.Errorf("transactionHashProjection must cover the transaction field union")
	}
	seen := make(map[string]bool)
	for i := 0; i < projection.NumFields(); i++ {
		wire, err := projectionWireName(projection, i)
		if err != nil {
			return nil, nil, err
		}
		f := projection.Field(i)
		if union[wire] == nil || seen[wire] {
			return nil, nil, fmt.Errorf("invalid transactionHashProjection key %q", wire)
		}
		seen[wire] = true
		if wire == "TransactionHash" {
			if f.Name() != "TransactionHash" || !types.Identical(types.NewPointer(f.Type()), union[wire]) {
				return nil, nil, fmt.Errorf("transaction hash projection must hold the transaction's felt by value")
			}
		} else if !types.Identical(f.Type(), discard) {
			return nil, nil, fmt.Errorf("transactionHashProjection.%s must be discarded", f.Name())
		}
	}
	if err := emitFields(&schema, "TransactionHashProjection", []string{"TransactionHash"}); err != nil {
		return nil, nil, err
	}
	readers.WriteString(`
