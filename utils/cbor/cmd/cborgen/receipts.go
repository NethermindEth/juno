package main

import (
	"bytes"
	"fmt"
	"go/types"
	"strings"
)

// Receipt readers use concrete stores and preserve the planner's shared slice
// storage and fused ExecutionResources allocation. Schema drift is checked
// before emitting either code or immutable field tables.
func emitReceipts(p *types.Package) (*bytes.Buffer, *bytes.Buffer, error) {
	var readers, schema bytes.Buffer
	readers.WriteString(`// Code generated by cborgen; DO NOT EDIT.
package core
import (
 "github.com/NethermindEth/juno/core/internal/cborreceipts"
 "github.com/NethermindEth/juno/utils/cbor/cborerr"
 "github.com/NethermindEth/juno/utils/cbor/cursor"
 "github.com/NethermindEth/juno/utils/cbor/fastcbor"
)
`)
	schema.WriteString(`// Code generated by cborgen; DO NOT EDIT.
// Package cborreceipts owns immutable lookup tables for typed receipt readers.
package cborreceipts
import "github.com/NethermindEth/juno/utils/cbor/cursor"
`)
	for _, name := range []string{"BuiltinInstanceCounter", "DataAvailability", "GasConsumed", "ExecutionResources", "Event", "L1ToL2Message", "L2ToL1Message", "TransactionReceipt"} {
		st := p.Scope().Lookup(name).Type().Underlying().(*types.Struct)
		var names, reads, zeros []string
		for i := 0; i < st.NumFields(); i++ {
			wire, err := projectionWireName(st, i)
			if err != nil {
				return nil, nil, fmt.Errorf("%s: %w", name, err)
			}
			f := st.Field(i)
			read, zero, err := receiptField(f.Type())
			if err != nil {
				return nil, nil, fmt.Errorf("%s.%s: %w", name, f.Name(), err)
			}
			if name == "ExecutionResources" {
				switch f.Name() {
				case "DataAvailability":
					if read != "cborReadDataAvailabilityPointer" {
						return nil, nil, fmt.Errorf("ExecutionResources.DataAvailability changed shape")
					}
					read = "cborReadDataAvailabilitySlot"
				case "TotalGasConsumed":
					if read != "cborReadGasConsumedPointer" {
						return nil, nil, fmt.Errorf("ExecutionResources.TotalGasConsumed changed shape")
					}
					read = "cborReadGasConsumedSlot"
				}
			}
			call := read + "(c, &dst." + f.Name()
			switch read {
			case "cborReadDataAvailabilitySlot":
				call += ", availability"
			case "cborReadGasConsumedSlot":
				call += ", gas"
			}
			reads = append(reads, call+")")
			names = append(names, wire)
			zeros = append(zeros, "dst."+f.Name()+zero)
		}
		if err := emitFields(&schema, name, names); err != nil {
			return nil, nil, err
		}
		if name == "TransactionReceipt" {
			fmt.Fprintf(&readers, "\nfunc cborZero%s(dst *%s) bool { return %s }\n", name, name, strings.Join(zeros, " && "))
		}
		extra := ""
		if name == "ExecutionResources" {
			extra = ", availability *DataAvailability, gas *GasConsumed"
		}
		fmt.Fprintf(&readers, "\nfunc cborRead%s(c *cursor.Cursor, dst *%s%s) error {\ns,err:=cborreceipts.Open%s(c)\nfor err==nil {\nvar field int\nfield,err=c.NextField(&s)\nswitch field {\ncase cursor.Done: return err\n", name, name, extra, name)
		for i, read := range reads {
			fmt.Fprintf(&readers, "case %d: err=%s\n", i, read)
		}
		readers.WriteString("default: err=c.Skip()\n}\n}\nreturn err\n}\n")
	}
	// Only ExecutionResources has eligible distinct small children. Statically
	// retaining both slots matches the planner's 32-byte child/64-byte total rule.
	readers.WriteString(`
type cborExecutionResourcesBlock struct {
 Value ExecutionResources
 Availability DataAvailability
 Gas GasConsumed
}
func cborReadExecutionResourcesPointer(c *cursor.Cursor, dst **ExecutionResources) error {
 if c.Null() { *dst=nil; return nil }
 block:=new(cborExecutionResourcesBlock)
 if err:=cborReadExecutionResources(c,&block.Value,&block.Availability,&block.Gas);err!=nil {return err}
 *dst=&block.Value
 return nil
}
`)
	for _, name := range []string{"DataAvailability", "GasConsumed"} {
		fmt.Fprintf(&readers, `func cborRead%sSlot(c *cursor.Cursor, dst **%s, value *%s) error {
 if c.Null() { *dst=nil; return nil }
 if err:=cborRead%s(c,value);err!=nil {return err}
 *dst=value
 return nil
}
`, name, name, name, name)
	}
	for _, name := range []string{"L1ToL2Message", "TransactionReceipt"} {
		fmt.Fprintf(&readers, `func cborRead%sPointer(c *cursor.Cursor, dst **%s) error {
 if c.Null() { *dst=nil; return nil }
 value:=new(%s)
 if err:=cborRead%s(c,value);err!=nil {return err}
 *dst=value
 return nil
}
`, name, name, name, name)
	}
	for _, name := range []string{"Event", "L2ToL1Message"} {
		fmt.Fprintf(&readers, `// cborRead%[1]sPointers preserves the planner's bounded shared allocation.
func cborRead%[1]sPointers(c *cursor.Cursor, dst *[]*%[1]s) error {
 if c.Null() { *dst=nil; return nil }
 count,err:=c.ArrayLen()
 if err!=nil {return err}
 out:=make([]*%[1]s,count)
 shared:=min(count,c.Len()/32)
 values:=make([]%[1]s,shared)
 used:=0
 for i:=range out {
  if c.Null() {continue}
  var value *%[1]s
  if used<shared {value=&values[used];used++} else {value=new(%[1]s)}
  if err:=cborRead%[1]s(c,value);err!=nil {return err}
  out[i]=value
 }
 c.Leave()
 *dst=out
 return nil
}
`, name)
	}
	for _, entry := range []struct{ stem, typ, guard, zero, read string }{
		{"TransactionReceipt", "TransactionReceipt", "!cborZeroTransactionReceipt(dst)", "TransactionReceipt{}", "cborReadTransactionReceipt"},
		{"TransactionReceiptPointer", "*TransactionReceipt", "*dst!=nil", "nil", "cborReadTransactionReceiptPointer"},
	} {
		fmt.Fprintf(&readers, `func cborClear%[1]s(dst *%[2]s) { *dst=%[4]s }
// Decode%[1]sFirst decodes one receipt and returns the original unread suffix.
func Decode%[1]sFirst(data []byte, dst *%[2]s) ([]byte,error) {
 if %[3]s {return nil,&cborerr.DecodeError{Kind:cborerr.ErrUnsupported,Detail:"the destination is not the zero value"}}
 c:=cursor.NewCursor(data)
 if err:=%[5]s(&c,dst);err!=nil {cborClear%[1]s(dst);return nil,err}
 return c.Remaining(),nil
}
// Decode%[1]s requires exactly one receipt and clears the destination on parse failure.
func Decode%[1]s(data []byte, dst *%[2]s) error {
 rest,err:=Decode%[1]sFirst(data,dst)
 if err==nil && len(rest)!=0 {cborClear%[1]s(dst);return &cborerr.DecodeError{Kind:cborerr.ErrExtraneousData,Extra:len(rest)}}
 return err
}
`, entry.stem, entry.typ, entry.guard, entry.zero, entry.read)
	}
	readers.WriteString(`func registerTypedReceipts() {
 fastcbor.RegisterTyped[TransactionReceipt](DecodeTransactionReceiptFirst)
 fastcbor.RegisterTyped[*TransactionReceipt](DecodeTransactionReceiptPointerFirst)
}
`)
	return &readers, &schema, nil
}

func receiptField(t types.Type) (read, zero string, err error) {
	typ := types.TypeString(t, func(p *types.Package) string { return p.Path() })
	switch typ {
	case "uint64":
		return "cborReadUint64", " == 0", nil
	case "bool":
		return "cborReadBool", " == false", nil
	case "string":
		return "cborReadString", " == \"\"", nil
	case "github.com/NethermindEth/juno/core.FeeUnit":
		if !types.Identical(t.Underlying(), types.Typ[types.Uint8]) {
			break
		}
		return "cborReadFeeUnit", " == 0", nil
	case "*github.com/NethermindEth/juno/core/felt.Felt":
		return "cborReadFelt", " == nil", nil
	case "github.com/NethermindEth/juno/core/felt.Slice[github.com/NethermindEth/juno/core/felt.Felt]":
		return "cborReadFeltValues", " == nil", nil
	case "github.com/NethermindEth/juno/l1/eth.Address":
		array, ok := t.Underlying().(*types.Array)
		if !ok || array.Len() != 20 || !types.Identical(array.Elem(), types.Typ[types.Uint8]) {
			break
		}
		return "cborReadAddress", " == [20]byte{}", nil
	case "github.com/NethermindEth/juno/core.BuiltinInstanceCounter":
		return "cborReadBuiltinInstanceCounter", " == (BuiltinInstanceCounter{})", nil
	case "*github.com/NethermindEth/juno/core.ExecutionResources":
		return "cborReadExecutionResourcesPointer", " == nil", nil
	case "*github.com/NethermindEth/juno/core.DataAvailability":
		return "cborReadDataAvailabilityPointer", " == nil", nil
	case "*github.com/NethermindEth/juno/core.GasConsumed":
		return "cborReadGasConsumedPointer", " == nil", nil
	case "*github.com/NethermindEth/juno/core.L1ToL2Message":
		return "cborReadL1ToL2MessagePointer", " == nil", nil
	case "[]*github.com/NethermindEth/juno/core.Event":
		return "cborReadEventPointers", " == nil", nil
	case "[]*github.com/NethermindEth/juno/core.L2ToL1Message":
		return "cborReadL2ToL1MessagePointers", " == nil", nil
	}
	return "", "", fmt.Errorf("unmapped receipt field type %s", typ)
}
